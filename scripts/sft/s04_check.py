"""Step 6 of docs/prepare_sft_dataset.md: cheap automatic per-item checks before any validation call.

    python scripts/sft/s04_check.py --level easy

Reads 02_items/items_raw.jsonl, writes 03_checked/passed.jsonl and rejected.jsonl (with reason codes) and prints the
reject rate per reason and subject. A reason above 10% means: fix the generator prompt, not just the items.
"""
import argparse
import difflib
import re
from collections import Counter, defaultdict

from sft_common import (Paths, ensure_dirs, has_marker, level_arg, load_config, norm, nozwj, read_jsonl,
                        sinhala_ratio, stdout_utf8, update_manifest, words, write_jsonl)

BANNED_REFS = ["ඉහත ඡේද", "ඡේදයට අනුව", "පාඩමේ", "පාඩමෙහි", "පාඩමට අනුව", "රූපය", "රූප සටහන", "රූපයේ", "වගුව",
               "වගුවේ", "ක්‍රියාකාරකම", "පිටුව", "ඉහත කොටස", "පෙළ පොත", "පෙළපොත", "සිතියම"]
NEGATION = ["නොවන", "නොවේ", "සාවද්‍ය", "වැරදි", "අසත්‍ය", "නොගැළපෙන", "නොගැලපෙන", "නොමැති", "අයත් නො",
            "නොකරන", "නොකෙරෙන", "නොයෙදෙන", "නොහැකි", "නොදක්වන", "නොසැලකෙන"]
ALL_NONE = ["ඉහත සියල්ල", "ඉහත කිසිවක්", "සියල්ලම", "සියල්ල ම", "කිසිවක් නොවේ"]
ABSOLUTE = ["සෑම විටම", "සෑම විට ම", "කිසිවිටෙක", "කිසි විටෙක", "පමණක්", "කිසිසේත්"]
# common words that are no answer cue when shared by stem and key (compared without ZWJ, like words())
STOP = {nozwj(w) for w in ["කිරීම", "කිරීමයි", "යුතු", "යුතුය", "විය", "වේ", "වන", "වූ", "ඇති", "ඇත", "නිසා", "සඳහා",
                           "පිළිබඳ", "අතර", "මෙම", "එම", "සහ", "ලෙස", "විට", "කරන", "කළ", "හැකි", "බව", "බවයි", "නොවේ",
                           "මගින්", "විසින්", "තුළ", "වශයෙන්", "කිහිපයක්", "දෙක", "තුන", "පහත", "ඉහත"]}
BLANK_RE = re.compile(r"\.{3,}|…|_{3,}")
ARTEFACT_RE = re.compile(r"[•À-ÿ�]|එ්")


def check(item: dict, section_text: str, cfg: dict) -> list[str]:
    c = cfg["checks"]
    m = item["metadata"]
    qtype = m["qtype"]
    stem, opts, ans = item["question"], item["choices"], item["answer"]
    key = opts[ans - 1]
    dis = [o for i, o in enumerate(opts) if i != ans - 1]
    r = []
    # schema
    if len(opts) != 4 or not all(o.strip() for o in opts) or not 1 <= ans <= 4:
        r.append("schema")
        return r
    if len({norm(o) for o in opts}) < 4:
        r.append("duplicate_options")
    # one option's words are a proper subset of another's, i.e. it contains the whole other option
    # (e.g. "මාර්ගය" vs "ප්‍රධාන මාර්ගය"). Compare whole WORD tokens, not raw characters: in Sinhala
    # "හිස්"/"දණහිස්" and "කුසල කර්ම"/"අකුසල කර්ම" share letters but are different words. Keep every
    # token (do NOT drop short ones like words() does): 2-letter words such as ජන/දස/කළ/මව are the
    # distinguishing word in homogeneous option sets, and dropping them makes them look like subsets.
    ow = [{norm(w) for w in o.split()} - {""} for o in opts]
    if qtype != "combination" and any(a and a < b for a in ow for b in ow):
        r.append("option_contains_option")
    # script / encoding
    for t in [stem] + opts:
        if any(ch.isalpha() for ch in t) and sinhala_ratio(t) < c["min_sinhala_ratio"] and qtype != "combination":
            r.append("not_sinhala")
            break
    if ARTEFACT_RE.search(stem + " ".join(opts)):
        r.append("fm_artefact")
    # evidence
    quotes = [m.get("evidence", "")] if qtype != "combination" else [s["evidence"] for s in m.get("statements", [])]
    src = norm(section_text)
    if any(not q or norm(q) not in src for q in quotes):
        r.append("evidence_not_in_section")
    # self-contained
    if has_marker(stem, BANNED_REFS) or any(has_marker(o, BANNED_REFS) for o in opts):
        r.append("refers_to_text_or_figure")
    # length
    smax = c["combination_stem_max_chars"] if qtype == "combination" else c["stem_max_chars"]
    if not c["stem_min_chars"] <= len(stem) <= smax:
        r.append("stem_length")
    if any(len(o) > c["option_max_chars"] for o in opts) and qtype != "statement":
        r.append("option_length")
    if qtype == "statement" and any(len(o) > 2 * c["option_max_chars"] for o in opts):
        r.append("option_length")
    # cues (not for combination: its options are generated by code)
    if qtype != "combination":
        lens = [len(o) for o in opts]
        if max(lens) >= c["length_cue_min_chars"] and len(key) > c["length_cue_ratio"] * max(len(d) for d in dis):
            r.append("key_much_longer")
        kw, sw = words(key) - STOP, words(stem) - STOP
        dw = set().union(*(words(d) for d in dis))
        if qtype != "statement" and {w for w in (kw & sw) - dw if len(w) >= 4}:
            r.append("clang_cue")
        if has_marker(" ".join(opts), ALL_NONE):
            r.append("all_or_none_of_above")
        if any(has_marker(d, ABSOLUTE) for d in dis) and not has_marker(key, ABSOLUTE):
            r.append("absolute_word_in_distractor_only")
        if len(norm(key)) >= 4 and norm(key) in norm(stem):
            r.append("key_in_stem")
        ends = [o.rstrip().endswith(".") for o in opts]
        if sum(ends) in (1, 3) and ends[ans - 1] == (sum(ends) == 1):     # the key is the odd one out
            r.append("key_punctuation_differs")
    # type-specific
    if qtype == "negation" and not has_marker(stem, NEGATION):
        r.append("negation_without_marker")
    if qtype == "blank" and not BLANK_RE.search(stem):
        r.append("blank_without_dots")
    if qtype == "combination":
        closing = m.get("closing", "")
        c_ = nozwj(closing)
        # must ask for the TRUE statements ("නිවැරදි වන්නේ"); note "නිවැරදි" itself contains "වැරදි"
        if "නිවැරදි" not in c_ or "නිවැරදි නොවන" in c_ or re.search("(?<!නි)වැරදි", c_):
            r.append("combination_closing_not_true_set")
    return r


def main():
    ap = argparse.ArgumentParser(description="Automatic per-item checks")
    level_arg(ap)
    args = ap.parse_args()
    stdout_utf8()
    paths, cfg = Paths(args.level), load_config(args.level)
    ensure_dirs(paths)
    sections = {s["id"]: s["text"] for s in read_jsonl(paths.plan / "sections.jsonl")}
    items = list(read_jsonl(paths.items / "items_raw.jsonl"))
    passed, rejected = [], []
    by_job = defaultdict(list)
    for it in items:
        text = "\n\n".join(sections[s] for s in it["metadata"]["source_ids"])
        reasons = check(it, text, cfg)
        by_job[it["metadata"]["job_id"]].append((it, reasons))
    # near-duplicate stems inside one job: keep the first
    for jid, rows in by_job.items():
        kept = []
        for it, reasons in rows:
            if not reasons:
                if any(difflib.SequenceMatcher(None, norm(it["question"]), norm(k["question"])).ratio()
                       > cfg["checks"]["job_duplicate_ratio"] for k in kept):
                    reasons.append("duplicate_in_job")
                else:
                    kept.append(it)
            (passed if not reasons else rejected).append(it if not reasons else {**it, "reject_reasons": reasons})
    passed.sort(key=lambda x: x["id"])
    rejected.sort(key=lambda x: x["id"])
    write_jsonl(paths.checked / "passed.jsonl", passed)
    write_jsonl(paths.checked / "rejected.jsonl", rejected)

    n = len(items) or 1
    reasons = Counter(r for it in rejected for r in it["reject_reasons"])
    print(f"items {len(items)}: passed {len(passed)} ({100 * len(passed) / n:.1f}%), rejected {len(rejected)}")
    warn = cfg["checks"]["reason_warn_share"]
    for r, k in reasons.most_common():
        flag = "   <-- above 10%: fix the generator prompt" if k / n > warn else ""
        print(f"  {r:<36}{k:>6} ({100 * k / n:.1f}%){flag}")
    subj = Counter(it["subject"] for it in items)
    rej = Counter(it["subject"] for it in rejected)
    print("reject rate per subject:", ", ".join(f"{s} {100 * rej[s] / subj[s]:.0f}%" for s in sorted(subj)))
    qt = Counter(it["metadata"]["qtype"] for it in items)
    rq = Counter(it["metadata"]["qtype"] for it in rejected)
    print("reject rate per type:   ", ", ".join(f"{t} {100 * rq[t] / qt[t]:.0f}%" for t in sorted(qt)))
    update_manifest(paths, "checks", {"items": len(items), "passed": len(passed), "reasons": dict(reasons)})
    print(f"-> {paths.checked}")


if __name__ == "__main__":
    main()
